import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), "utf8");
const start = read("app/api/auth/link-email/route.ts");
const verify = read("app/api/auth/link-email/verify/route.ts");
const steam = read("app/api/auth/steam/route.ts");
const callback = read("app/api/auth/steam/callback/route.ts");
const completion = read("lib/profile-completion.ts");
const profileApi = read("app/api/profile/route.ts");
const frameApi = read("app/api/profile/frame/route.ts");
const schema = read("prisma/schema.prisma");
const migration = read("prisma/migrations/20261027200000_profile_frame_equipment/migration.sql");
const profileUi = read("app/profile/page.tsx");
const inventoryUi = read("app/inventory/page.tsx");
assert.match(start, /getCurrentUser\(\)/, "email linking requires authenticated session");
assert.match(start, /randomBytes\(32\)\.toString\("hex"\)/, "email verification uses a cryptographically strong token");
assert.match(start, /purpose: "EMAIL_LINK"/, "email link uses dedicated purpose");
assert.match(start, /expiresAt: new Date\(now\.getTime\(\) \+ 10 \* 60_000\)/, "email token expires");
assert.match(start, /EMAIL_LINK_USER/); assert.match(start, /EMAIL_LINK_IP/);
assert.match(start, /mode: "insensitive"/, "email conflicts are case insensitive");
assert.match(verify, /userId: user\.id, purpose: "EMAIL_LINK"/, "token is consumed only for the server-bound account");
assert.match(verify, /record\.userId/, "confirmation derives account identity from server-side token record");
assert.match(verify, /usedAt: null, expiresAt: \{ gt: new Date\(\) \}/, "expired and reused tokens rejected");
assert.match(verify, /isolationLevel: "Serializable"/, "verification is transactional");
assert.match(verify, /EMAIL_LINK_COMPLETED/, "successful linking is audited");
assert.match(steam, /STEAM_LINK_STATE_ISSUED/); assert.match(callback, /consumeLinkState\(/);
assert.match(completion, /hasBothBindings: boolean/); assert.match(completion, /id: "accountBindings"/);
assert.match(profileApi, /cosmeticPurchase\.upsert/, "profile reward enters existing cosmetic inventory idempotently");
assert.match(schema, /equippedFrameItemId String\? @db\.Uuid/);
assert.match(frameApi, /FRAME_NOT_OWNED/, "only owned frames may be equipped");
assert.match(frameApi, /equippedFrameItemId: itemId/, "frame selection persists on user record");
assert.match(migration, /ON CONFLICT \("userId", "itemId"\) DO NOTHING/, "backfill does not duplicate prior rewards");
for (const lang of ["RU", "UA", "EN", "PL"]) { assert.ok(profileUi.includes(`${lang}:{`), `profile UI contains ${lang} localization`); }
assert.match(inventoryUi, /api\/profile\/frame/); assert.match(inventoryUi, /frameText\.remove/); assert.match(inventoryUi, /frameText\.wear/);
console.log("Email/Steam linking and profile-frame source-contract checks: PASS (22 assertions)");
