import assert from "node:assert/strict";
import fs from "node:fs";
const read=(p)=>fs.readFileSync(p,"utf8");
const api=read("app/api/challenges/route.ts");
const page=read("app/challenges/page.tsx");
const notifications=read("app/notifications/page.tsx");
const leagues=read("lib/leagues.ts");
const analytics=read("app/api/analytics/route.ts");
const search=read("app/api/search/route.ts");
assert.match(api,/row\.status === "ACCEPTED" && row\.matchId/,"repeat accept returns linked match");
assert.match(api,/where: \{ id: row\.matchId \}, select: \{ id: true, status: true \}/,"repeat accept loads existing match only");
assert.match(api,/Cache-Control": "private, no-store"/,"personal challenges are not publicly cached");
assert.match(api,/row\.receiverId !== me\.id \|\| row\.status !== "PENDING"/,"only recipient can accept pending challenge");
assert.match(api,/row\.senderId !== me\.id \|\| row\.status !== "PENDING"/,"only sender can cancel pending challenge");
assert.match(notifications,/n\.type==="CHALLENGE"&&n\.payload\?\.challengeId/,"challenge notification links to specific challenge");
assert.match(page,/`\/matches\/\$\{encodeURIComponent\(x\.matchId\)\}`/,"accepted challenge opens exact match");
assert.match(page,/ru:\{title:"Вызовы"/,"Russian labels exist");
assert.match(page,/ua:\{title:"Виклики"/,"Ukrainian labels exist");
assert.match(page,/en:\{title:"Challenges"/,"English labels exist");
assert.match(page,/pl:\{title:"Wyzwania"/,"Polish labels exist");
assert.match(leagues,/SILVER: 1200/);assert.match(leagues,/GOLD: 1400/);assert.match(leagues,/DIAMOND: 1600/);assert.match(leagues,/ELITE: 1800/);
assert.match(analytics,/match: \{ status: "FINISHED", economyMode: "REAL" \}/,"analytics history filters to finished REAL matches");
assert.match(analytics,/take: 50/,"recent analytics history is limited to 50 rows");
assert.match(search,/if\(q\.length<2\)/,"global search rejects too-short query");
assert.match(search,/status:'ACTIVE',isTestAccount:false/,"search excludes inactive/test accounts");
