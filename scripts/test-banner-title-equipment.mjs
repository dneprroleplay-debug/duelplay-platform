import { readFileSync, existsSync } from 'node:fs';
import assert from 'node:assert/strict';
const read = p => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const schema = read('prisma/schema.prisma');
const migration = read('prisma/migrations/20261028120000_banner_title_equipment/migration.sql');
const api = read('app/api/profile/cosmetics/route.ts');
const ownProfile = read('app/api/profile/route.ts');
const publicProfile = read('app/api/profile/[nickname]/route.ts');
const inventory = read('app/inventory/page.tsx');
const component = read('components/Common/CosmeticEquipment.tsx');
assert.match(schema, /equippedBannerItemId\s+String\? @db\.Uuid/);
assert.match(schema, /equippedTitleItemId\s+String\? @db\.Uuid/);
assert.match(migration, /REFERENCES "CosmeticItem"\("id"\) ON DELETE SET NULL/);
assert.match(api, /userId_itemId: \{ userId: user\.id, itemId \}/, 'ownership lookup must be scoped to the current user');
assert.match(api, /owned\.item\.type !== type/, 'equipment type must be checked server-side');
assert.match(api, /equippedBannerItemId|equippedTitleItemId/);
assert.match(ownProfile, /equippedBanner:/);
assert.match(publicProfile, /equippedBanner:/);
assert.match(publicProfile, /equippedTitle:u\.equippedTitleItem/);
assert.match(inventory, /<CosmeticEquipment\s*\/>/);
for (const word of ['RU:', 'UA:', 'EN:', 'PL:', 'Equip', 'Remove']) assert.ok(component.includes(word), `missing localized equipment support: ${word}`);
assert.ok(existsSync(new URL('../public/images/banners/pink-arena-banner.svg', import.meta.url)));
assert.match(read('app/api/shop/route.ts'), /isRewardOnlyCosmetic/, 'existing reward-only shop protection must remain');
assert.match(read('lib/cosmetic-frame-image.ts'), /cosmeticFrameImageUrl/, 'existing frame asset handling must remain');
console.log('Banner/title equipment source-contract checks: PASS');
