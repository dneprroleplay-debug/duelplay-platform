import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { verificationEmailHtml, verificationEmailText } from '../lib/auth-email-templates.ts';
const read = (p) => readFileSync(new URL(`../${p}`, import.meta.url), 'utf8');
const own = read('app/profile/page.tsx');
const pub = read('app/profile/[nickname]/page.tsx');
const api = read('app/api/profile/[nickname]/route.ts');
const inventory = read('components/Common/CosmeticEquipment.tsx');
const component = read('components/Common/ProfileBanner.tsx');
const css = read('app/globals.css');
const email = read('app/api/auth/verify-email/route.ts');
const html = verificationEmailHtml('QAPlayer', 'AB12CD');
const text = verificationEmailText('QAPlayer', 'AB12CD');
assert.match(own, /themeId=\{data\.user\.themePreference\}/, 'own banner must use owner theme');
assert.match(pub, /themeId=\{p\.themePreference\}/, 'public banner must use profile owner theme, not viewer theme');
assert.match(api, /themePreference:true/, "public profile API selects the owner theme");
assert.match(api, /themePreference:u\.themePreference/, "public profile API returns the owner theme");
assert.match(component, /themeById\(typeof themeId === "string" \? themeId : "STANDARD"\)/, 'unknown theme safely falls back to STANDARD');
assert.match(component, /--dp-banner-trail.*accent/s, 'active theme accent is used for trail color');
assert.match(css, /@keyframes dp-banner-perimeter/, 'perimeter trail animation exists');
assert.match(css, /prefers-reduced-motion:reduce\)\{\.dp-profile-banner__trail rect\{animation:none!important/, 'reduced motion stops the moving trail');
assert.match(inventory, /ProfileBanner imageUrl=\{item\.imageUrl\}.*compact/s, 'inventory banner preview uses shared renderer');
assert.match(html, /href="https:\/\/duelplaygame\.com\/verify-email#code=AB12CD"/, 'email CTA has correct verification URL fragment');
assert.match(html, /10 минут/, 'HTML states the 10-minute lifetime');
assert.match(html, /support@duelplaygame\.com/, 'HTML includes support address');
assert.match(text, /support@duelplaygame\.com/, 'plain text includes support address');
assert.match(text, /AB12CD/, 'plain text includes verification code');
assert.match(text, /https:\/\/duelplaygame\.com\/verify-email#code=AB12CD/, 'plain text includes correct verification link');
assert.match(email, /usedAt|expiresAt/, 'verification endpoint retains token lifecycle handling');
console.log('Profile banner theme + email preview contract: 16/16 PASS');
